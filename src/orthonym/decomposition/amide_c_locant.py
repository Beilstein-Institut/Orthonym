"""The C-locant of a substituted acetamide assembled from the name of its acid (PB-W).

The acid fragment of an amide split is named as the free acid, and a free acid cites no locant for
the group on its one substitutable carbon: 'chloroacetic acid', '(thiophen-2-yl)acetic acid'. The
amide made from it has a nitrogen that can carry a substituent as well, so the same group could
stand on the nitrogen and the locant is essential.

 (the Blue Book, heading " Omission of locants"): "Locants are omitted
when no isomer can be generated by moving suffixes and/or prefixes (if any) from their position to
another or by interchanging them between two different positions." The Blue Book's own amides cite
it: '2-amino-N-(2,3-dihydroxypropyl)-N-methylacetamide (PIN)' (:33576), 'N-carbamoyl-2-
phenylacetamide (PIN)' (:33364). The amide of the acid names printed without the locant
('(thiophen-2-yl)acetamide' for '2-(thiophen-2-yl)acetamide') omits one that (:2869)
makes essential: "if any locants are essential for defining the structure of the parent structure
or of a unit of structure... then all locants must be cited".
"""
from __future__ import annotations

from typing import Optional

from rdkit import Chem

_ACETAMIDE = "acetamide"
#: the carboxyl carbon of the acid fragment and the carbon it carries
_CARBOXYL = Chem.MolFromSmarts("[CX3](=O)([OX2H1])[CX4]")


def amide_with_c_locant(amide_name: str, acid_smiles: Optional[str]) -> Optional[str]:
    """``amide_name`` (the acid's name turned into an amide name) with the locant of the group on
    C-2 cited, or ``None`` when the amide cannot be cited with confidence.

    Unchanged: a name that is not a substituted acetamide ('propanamide', 'acetamide'), and one
    that already begins with a locant ('2-chloroacetamide'). ``'2-' + name`` when the acid has one
    group on its alpha carbon. ``None`` for two or three groups on it (the citation order of
    several prefixes with a shared locant is not decided here), for a name that begins with a
    stereodescriptor block, and when the structure of the acid is not at hand: the caller then
    builds no amide from this split and another producer names the molecule."""
    if not amide_name.endswith(_ACETAMIDE) or amide_name == _ACETAMIDE:
        return amide_name
    if amide_name[0].isdigit():
        return amide_name
    if not acid_smiles:
        return None
    mol = Chem.MolFromSmiles(acid_smiles)
    match = mol.GetSubstructMatches(_CARBOXYL) if mol is not None else ()
    if len(match) != 1:
        return None
    alpha = mol.GetAtomWithIdx(match[0][3])
    heavy = [a for a in alpha.GetNeighbors() if a.GetIdx() != match[0][0] and a.GetAtomicNum() > 1]
    if len(heavy) != 1 or _has_front_stereo(amide_name):
        return None
    return f"2-{amide_name}"


def _has_front_stereo(name: str) -> bool:
    """True when ``name`` begins with a stereodescriptor block such as '(2S)-' or '(E)-'."""
    from .fragment_assembly import _FRONT_STEREO_RE
    return bool(_FRONT_STEREO_RE.match(name))
